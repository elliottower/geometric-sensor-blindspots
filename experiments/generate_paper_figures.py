def _get_noise_trajectory(seed):
    """Recompute raw geodesic trajectory for noise-axis sweep."""
    data_rng = np.random.default_rng(seed)
    proj_rng = np.random.default_rng(seed + 1000)

    z, y = generate_latent(N_SAMPLES_PER_CLASS, data_rng)
    U_base = generate_base_embedding(proj_rng)

    geos = []
    for step, noise in enumerate(NOISE_SWEEP_LEVELS):
        obs_rng = np.random.default_rng(seed * 100 + step)
        Xs = [generate_sensor_data(z, U_base, noise, obs_rng) for _ in range(3)]
        geo, _ = mean_edge_geodesics(Xs, PCA_K)
        geos.append(geo)
    return geos


