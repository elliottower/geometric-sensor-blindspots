# FIG 3 — Confound schematic
# ═════════════════════════════════════════════════════════════════
def fig3_confound_schematic():
    """Two-panel DAG — clean academic style matching the data plots."""
    print("  Generating confound schematic...")
    fig, axes = plt.subplots(1, 2, figsize=(6.5, 3.4),
                              gridspec_kw={"wspace": 0.4})

    NODE_W = 0.40
    NODE_H = 0.23

    def _node(ax, x, y, text, fc, ec, dashed=False):
        ls = (0, (4, 3)) if dashed else "-"
        lw = 0.6 if dashed else 0.8
        e = mpatches.Ellipse(
            (x, y), NODE_W, NODE_H, facecolor=fc,
            edgecolor=ec, linewidth=lw, linestyle=ls,
            zorder=4, clip_on=False,
        )
        ax.add_patch(e)
        txt_c = DAG_BLOCK_EC if dashed else ec
        ax.text(x, y, text, ha="center", va="center",
                fontsize=8, color=txt_c, zorder=5, clip_on=False)

    def _arrow(ax, x1, y1, x2, y2, color, lw=0.8, dashed=False):
        ls_val = (0, (4, 3)) if dashed else "-"
        ax.annotate(
            "", xy=(x2, y2), xytext=(x1, y1),
            arrowprops=dict(
                arrowstyle="-|>", color=color, lw=lw,
                linestyle=ls_val, mutation_scale=8,
                shrinkA=1, shrinkB=1,
            ),
            zorder=3, clip_on=False,
        )

    TOP, MID, BOT = 0.85, 0.50, 0.15
    LEFT, RIGHT, CEN = 0.25, 0.75, 0.50
    RH = NODE_H / 2

    for ax in axes:
        ax.set_xlim(-0.05, 1.05)
        ax.set_ylim(-0.05, 1.05)
        ax.set_aspect("equal")
        ax.axis("off")

    # ── Panel a: Confounded ───────────────────────────
    ax = axes[0]
    _node(ax, CEN, TOP, r"$\varepsilon$", "#F0F0F0", "#555555")
    _node(ax, LEFT, MID, "Observation\nnoise", DAG_RED_FC, DAG_RED_EC)
    _node(ax, RIGHT, MID, "Embedding\ndivergence", DAG_GRN_FC, DAG_GRN_EC)
    _node(ax, CEN, BOT, "Geodesic", DAG_RED_FC, DAG_RED_EC)

    _arrow(ax, CEN - 0.07, TOP - RH, LEFT + 0.07, MID + RH,
           color=DAG_RED_EC)
    _arrow(ax, CEN + 0.07, TOP - RH, RIGHT - 0.07, MID + RH,
           color=DAG_GRN_EC)
    _arrow(ax, LEFT + 0.07, MID - RH, CEN - 0.07, BOT + RH,
           color=DAG_RED_EC)
    _arrow(ax, RIGHT - 0.07, MID - RH, CEN + 0.07, BOT + RH,
           color=DAG_GRN_EC)

    ax.set_title("Confounded design", fontsize=9.5, fontweight="bold",
                 color="#333", pad=6)

    # ── Panel b: Orthogonal ───────────────────────────
    ax = axes[1]
    _node(ax, LEFT, TOP, r"$\sigma$" + "\n(fixed)", "#F0F0F0", "#555555")
    _node(ax, RIGHT, TOP, r"$\varepsilon_\mathrm{pert}$",
          DAG_GRN_FC, DAG_GRN_EC)
    _node(ax, LEFT, MID, "Observation\nnoise", DAG_BLOCK_FC, DAG_BLOCK_EC,
          dashed=True)
    _node(ax, RIGHT, MID, "Embedding\ndivergence", DAG_GRN_FC, DAG_GRN_EC)
    _node(ax, CEN, BOT, "Geodesic", DAG_BLUE_FC, DAG_BLUE_EC)

    _arrow(ax, LEFT, TOP - RH, LEFT, MID + RH,
           color=DAG_BLOCK_EC, lw=0.5, dashed=True)
    _arrow(ax, RIGHT, TOP - RH, RIGHT, MID + RH,
           color=DAG_GRN_EC)
    _arrow(ax, LEFT + 0.07, MID - RH, CEN - 0.07, BOT + RH,
           color=DAG_BLOCK_EC, lw=0.5, dashed=True)
    _arrow(ax, RIGHT - 0.07, MID - RH, CEN + 0.07, BOT + RH,
           color=DAG_GRN_EC)

    ax.text(LEFT - 0.01, (MID + BOT) / 2,
            "held constant", ha="right", va="center",
            fontsize=6, color=DAG_BLOCK_EC,
            clip_on=False)

    ax.set_title("Orthogonal design", fontsize=9.5, fontweight="bold",
                 color="#333", pad=6)


    fig.savefig(OUT / "b2_confound_schematic.pdf")
    fig.savefig(OUT / "b2_confound_schematic.png")
    plt.close(fig)
    print(f"  Saved: {OUT / 'b2_confound_schematic.png'}")


